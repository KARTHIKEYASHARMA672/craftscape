export function getBlockDef(id) {
  return BLOCK_BY_ID[id] ?? BLOCK_BY_ID[BLOCK.AIR];
}

export function isBlockSolid(id) {
  return (BLOCK_BY_ID[id]?.solid) === true;
}

export function isBlockOpaque(id) {
  return (BLOCK_BY_ID[id]?.opaque) === true;
}

export function isBlockLiquid(id) {
  return (BLOCK_BY_ID[id]?.liquid) === true;
}
