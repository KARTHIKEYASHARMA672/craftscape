function defBlock(partial) {
  const top = partial.top ?? partial.tile ?? 0;
  const bottom = partial.bottom ?? partial.tile ?? top;
  const side = partial.side ?? partial.tile ?? top;
  const front = partial.front ?? side;
  return Object.freeze({
    solid: true,
    opaque: true,
    transparent: false,
    liquid: false,
    replaceable: false,
    renderType: 'cube',
    hardness: 1.5,
    tool: 'any', // 'any' | 'pickaxe' | 'axe' | 'shovel'
    minTier: 0, // 0=hand, 1=wood, 2=stone, 3=iron, 4=diamond
    lightLevel: 0,
    flammable: false,
    interactive: false,
    soundGroup: 'stone',
    mapColor: '#7f868f',
    ...partial,
    tiles: Object.freeze({
      top,
      bottom,
      north: front,
      south: side,
      east: side,
      west: side,
    }),
    dropId: partial.dropId === undefined ? partial.id : partial.dropId,
    dropCount: partial.dropCount ?? 1,
  });
}

